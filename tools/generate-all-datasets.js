const fs = require('fs');
const path = require('path');

function saveDataset(filename, categoryKey, label, words) {
  // Deduplicate and normalize
  const map = new Map();
  words.forEach(item => {
    const raw = item.w.trim();
    const key = raw.toLowerCase().replace(/[-–—_]/g, ' ').replace(/\s+/g, ' ');
    if (!map.has(key)) {
      map.set(key, item);
    }
  });

  const uniqueWords = Array.from(map.values());

  const code = `(function(root, factory) {
  const data = factory();
  if (typeof module === 'object' && module.exports) {
    module.exports = data;
  }
  if (typeof root !== 'undefined') {
    root.KALAKOBANA_DATA = root.KALAKOBANA_DATA || {};
    root.KALAKOBANA_DATA['${categoryKey}'] = data;
  }
})(typeof globalThis !== 'undefined' ? globalThis : this, function() {
  return {
    category: "${categoryKey}",
    label: "${label}",
    words: ${JSON.stringify(uniqueWords, null, 2)}
  };
});
`;
  const filePath = path.join(__dirname, '..', 'data', filename);
  fs.writeFileSync(filePath, code, 'utf8');
  console.log(`Generated ${filename}: ${uniqueWords.length} words`);
}

function w(word, pop = 4, aliases = [], note = '') {
  return { w: word, popularity: pop, aliases, note };
}

